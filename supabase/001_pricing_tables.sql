drop policy if exists anon_read_currency_rates on public.currency_rates;
create policy anon_read_currency_rates on public.currency_rates for select to anon, authenticated using (true);
drop policy if exists anon_write_currency_rates on public.currency_rates;
create policy anon_write_currency_rates on public.currency_rates for all to anon, authenticated using (true) with check (true);

do $$
declare t text; begin
  foreach t in array array['price_lists','price_list_versions','price_list_parts','price_list_adders'] loop
    execute format('drop policy if exists anon_read_%1$s on public.%1$I', t);
    execute format('create policy anon_read_%1$s on public.%1$I for select to anon, authenticated using (true)', t);
    execute format('drop policy if exists anon_write_%1$s on public.%1$I', t);
    execute format('create policy anon_write_%1$s on public.%1$I for all to anon, authenticated using (true) with check (true)', t);
    execute format('grant select, insert, update, delete on public.%I to anon, authenticated', t);
  end loop;
end $$;
