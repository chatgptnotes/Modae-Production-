import { createHmac, randomUUID, timingSafeEqual } from 'node:crypto'
import { getAdminSupabaseClient } from './_supabase-client.js'
import { activeProfile } from './_user-roster.js'
import { isAccountAdmin } from '../src/userManagement.js'
import { backupSummary, cleanBackupValue, createBackupArchive, readBackupArchive, sha256, backupFileReferences, missingBackupFiles } from '../src/workspaceBackup.js'
import { readIntegrations } from './_ai-integrations.js'

const TABLES = ['approvals','audit','clarifications','leads','opportunities','price_list_versions','price_lists','proposals','records','settings','spares_lines','user_files']
const leases = new Map()
const ttl = 10 * 60 * 1000
const key = () => String(process.env.BACKUP_SIGNING_KEY || '')
const workspaceId = () => String(process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL || '').replace(/\/$/, '')
const signature = text => createHmac('sha256', key()).update(text).digest('hex')
const verify = async (text, value) => /^[a-f0-9]{64}$/.test(value || '') && timingSafeEqual(Buffer.from(signature(text), 'hex'), Buffer.from(value, 'hex'))
const fail = (message, status = 400) => Object.assign(new Error(message), { status })
const generationOf = snapshot => Number(snapshot.records.find(row => row.entity === 'state' && row.id === 'workspace_generation')?.data?.value || 0)
const decodeBytea = value => {
  if (!/^\\x[0-9a-f]*$/i.test(value || '') || value.length % 2 !== 0) throw fail('An uploaded document has invalid file bytes.')
  return new Uint8Array(Buffer.from(value.slice(2), 'hex'))
}
function lease(actor, value) {
  for (const [id, item] of leases) if (item.expires < Date.now()) leases.delete(id)
  if (leases.size >= 4) throw fail('Other backup operations are running. Retry shortly.', 429)
  const token = randomUUID(); leases.set(token, { ...value, actor, expires: Date.now() + ttl }); return token
}
function getLease(token, actor, type) {
  const value = leases.get(token)
  if (!value || value.actor !== actor || value.expires < Date.now() || value.type !== type) throw fail('Backup review expired. Select or export the backup again.', 409)
  return value
}
function validateDatabase(db) {
  if (!db || Object.keys(db).some(t => !TABLES.includes(t)) || TABLES.some(t => !Array.isArray(db[t]))) throw fail('Invalid backup database shape.')
  for (const [table, rows] of Object.entries(db)) {
    const ids = new Set()
    for (const row of rows) {
      const id = `${table === 'records' ? `${row.entity}/` : ''}${row.id}`
      if (typeof row.id !== 'string' || !row.id || row.id.length > 1000 || ids.has(id) || !Object.hasOwn(row, 'data') || (table === 'records' && !/^[a-z_]+$/.test(row.entity))) throw fail('Invalid or duplicate backup record identity.')
      ids.add(id)
    }
  }
}
const referenceKey = (kind, id, folder, name) => JSON.stringify([kind, id, folder || '', name])
function expectedFiles(database) {
  const stateFiles = database.records.find(row => row.entity === 'state' && row.id === 'files' && !row.deleted_at)?.data || {}
  return backupFileReferences({ leads: database.leads.filter(row => !row.deleted_at).map(row => ({ ...row.data, id: row.id })), opportunities: database.opportunities.map(row => ({ ...row.data, id: row.id })), files: stateFiles, config: database.settings.find(row => row.id === 'config' && !row.deleted_at)?.data || {} })
}
function filesFromSnapshot(snapshot) {
  const files = snapshot.user_files.map(row => {
    const { file_data, ...meta } = row
    const bytes = decodeBytea(file_data)
    if (bytes.length !== row.file_size) throw fail(`Incomplete document: ${row.file_name}`)
    return { meta: { ...meta, backend: 'supabase' }, bytes }
  })
  for (const ref of expectedFiles(snapshot)) if (ref.inline && missingBackupFiles([ref], files).length) {
    const match = /^data:([a-z0-9.+\-/]+);base64,([A-Za-z0-9+/]*={0,2})$/i.exec(ref.inline)
    if (!match) throw fail(`Invalid inline document: ${ref.file_name}`)
    const bytes = new Uint8Array(Buffer.from(match[2], 'base64'))
    if (bytes.length > 10 * 1024 * 1024) throw fail(`Document exceeds 10 MB: ${ref.file_name}`)
    const { inline, alternatives, ...meta } = ref
    files.push({ meta: { ...meta, backend: 'supabase', file_type: match[1], file_size: bytes.length, id: randomUUID() }, bytes })
  }
  return files
}
function sanitizedSnapshot(snapshot) {
  const out = cleanBackupValue(snapshot)
  out.user_files = []
  // Historical copies are not authoritative, and internal dependency clocks
  // are regenerated by triggers when data is restored.
  out.records = out.records.filter(row => row.entity !== 'approval_scope' && !TABLES.filter(t => t !== 'records').includes(row.entity))
  return out
}
function assertEmpty(snapshot) {
  if (['leads', 'opportunities', 'approvals', 'proposals', 'spares_lines', 'clarifications'].some(t => snapshot[t].some(row => !row.deleted_at)) || snapshot.user_files.length) throw fail('Restore requires an empty business workspace.')
  const names = new Set(['customers','leadArchive','vendorQuotes','svcEstimates','surveys','communications','files','kyc','poCompare','handover','bSteps'])
  if (snapshot.records.some(row => row.entity === 'state' && !row.deleted_at && names.has(row.id) && !['[]','{}','null'].includes(JSON.stringify(row.data)))) throw fail('Restore requires an empty business workspace.')
}
export function createAdminBackupsHandler(getClient = getAdminSupabaseClient) {
  return async (req, res) => {
    res.setHeader('Cache-Control', 'no-store')
    if (req.method !== 'POST') return res.status(405).json({ error: 'POST only' })
    const client = getClient()
    if (!client) return res.status(503).json({ error: 'Shared backups require a configured Supabase workspace.' })
    try {
      const token = String(req.headers?.authorization || '').replace(/^Bearer\s+/i, '').trim()
      if (!token) throw fail('Sign in to manage backups.', 401)
      const { data, error } = await client.auth.getUser(token)
      if (error || !data?.user) throw fail('Your session expired.', 401)
      const actor = await activeProfile(client, data.user)
      if (!actor || !isAccountAdmin(actor)) throw fail('Only active administrators can manage backups.', 403)
      if (key().length < 32) throw fail('Configure BACKUP_SIGNING_KEY with at least 32 random characters on the server.', 503)
      const operation = req.body?.operation
      const snapshot = async () => { const result = await client.rpc('workspace_backup_snapshot'); if (result.error) throw result.error; return result.data }
      if (operation === 'prepare-export') {
        const db = await snapshot()
        const integration = await readIntegrations(client)
        const id = lease(data.user.id, { type: 'export', snapshot: db, modelSettings: { text: integration.text, document: integration.document } })
        const references = missingBackupFiles(expectedFiles(db), filesFromSnapshot(db)).map(({ inline, ...ref }) => ref)
        return res.status(200).json({ token: id, references, opportunities: db.opportunities.map(r => ({ id: r.id, ...r.data })) })
      }
      if (operation === 'export') {
        const item = getLease(req.body.token, data.user.id, 'export'), db = item.snapshot
        const files = filesFromSnapshot(db)
        for (const file of req.body.externalFiles || []) {
          if (!['sharepoint','indexeddb'].includes(file.meta?.backend) || !['opportunity', 'attachment'].includes(file.meta.record_type) || typeof file.base64 !== 'string') throw fail('Invalid external document.')
          const bytes = new Uint8Array(Buffer.from(file.base64, 'base64'))
          if (bytes.length > 10 * 1024 * 1024) throw fail('A document exceeds the 10 MB storage limit.')
          const index = files.findIndex(({ meta }) => referenceKey(meta.record_type, meta.record_id, meta.folder, meta.file_name) === referenceKey(file.meta.record_type, file.meta.record_id, file.meta.folder, file.meta.file_name))
          // Match Folders: restored database originals remain authoritative
          // until an explicit replacement retires them.
          if (index >= 0) continue
          files.push({ meta: { ...cleanBackupValue(file.meta), id: randomUUID(), user_id: data.user.id, file_size: bytes.length }, bytes })
        }
        const missing = missingBackupFiles(expectedFiles(db), files)
        if (missing.length) throw fail(`Full backup blocked. Missing document bytes: ${missing.map(f => `${f.record_id}/${f.folder}/${f.file_name}`).join(', ').slice(0, 3000)}`)
        const sanitized = sanitizedSnapshot(db)
        const profiles = sanitized.records.find(r => r.entity === 'state' && r.id === 'users')?.data || []
        const result = await createBackupArchive({ payload: { database: sanitized, profiles, modelSettings: item.modelSettings }, files, source: { kind: 'connected', workspaceId: workspaceId(), generation: generationOf(db) }, sign: async text => signature(text) })
        leases.delete(req.body.token)
        return res.status(200).json({ archive: Buffer.from(result.bytes).toString('base64') })
      }
      if (operation === 'preview') {
        if (typeof req.body.archive !== 'string' || req.body.archive.length > 140 * 1024 * 1024) throw fail('Select a backup ZIP up to 100 MB.')
        const backup = await readBackupArchive(new Uint8Array(Buffer.from(req.body.archive, 'base64')), { connected: true, workspaceId: workspaceId(), verify })
        validateDatabase(backup.payload.database)
        const current = await snapshot(); assertEmpty(current)
        const summary = backupSummary(backup)
        const currentProfiles = current.records.find(r => r.entity === 'state' && r.id === 'users')?.data || []
        summary.accountMappings = summary.profiles.map(profile => ({ name: profile.name, email: profile.email, matched: currentProfiles.some(user => user.id === profile.id || String(user.email).toLowerCase() === String(profile.email).toLowerCase()) }))
        summary.settingsChanges = backup.payload.database.settings.filter(r => !r.id.startsWith('opportunity_')).map(r => r.id)
        const id = lease(data.user.id, { type: 'restore', backup, generation: generationOf(current), snapshotHash: await sha256(JSON.stringify(current)), expectedSnapshot: current })
        return res.status(200).json({ token: id, summary })
      }
      if (operation === 'restore') {
        const item = getLease(req.body.token, data.user.id, 'restore'), backup = item.backup
        const current = await snapshot(); assertEmpty(current)
        if (await sha256(JSON.stringify(current)) !== item.snapshotHash) throw fail('The workspace changed after review. Preview the backup again.', 409)
        const files = backup.files.map(({ meta, bytes }) => ({ ...meta, user_id: meta.user_id || data.user.id, file_size: bytes.length, hex: Buffer.from(bytes).toString('hex') }))
        const restored = await client.rpc('restore_workspace_backup', { p_generation: item.generation, p_database: backup.payload.database, p_files: files, p_actor: data.user.id, p_digest: backup.digest, p_expected_snapshot: item.expectedSnapshot })
        if (restored.error) throw restored.error
        leases.delete(req.body.token)
        return res.status(200).json(restored.data)
      }
      throw fail('Unknown backup operation.')
    } catch (error) {
      const status = error.status || (error.code === '40001' ? 409 : error.code === '22023' ? 400 : 503)
      return res.status(status).json({ error: error.status || ['40001','22023'].includes(error.code) ? error.message : 'Backup could not complete. Check the backup migration and retry. No partial restore was committed.' })
    }
  }
}
export default createAdminBackupsHandler()
