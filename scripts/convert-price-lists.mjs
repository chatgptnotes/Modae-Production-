// One-off converter: supplier price-list workbooks -> the seeded catalogue
// modules read by src/seed.js. Run by hand when a new supplier file lands:
//
//   node scripts/convert-price-lists.mjs "<bnk.xlsx>" "<metrix.xlsx>"
//
// The extraction itself lives in src/priceListImport.js, which is also what the
// in-app "Upload new version" path uses — so a file that seeds well here
// uploads the same way, and neither can quietly drift from the other.
import fs from 'node:fs'
import path from 'node:path'
import XLSX from 'xlsx-js-style'
import { extractSupplierWorkbook } from '../src/priceListImport.js'

const banner = source => `// GENERATED by scripts/convert-price-lists.mjs — do not edit by hand.
// Source workbook: ${source}
// Prices are the supplier file's placeholder values, not quotable figures.
`

function convert(file, exportName, outFile, defaultCurrency) {
  const result = extractSupplierWorkbook(XLSX.readFile(file), defaultCurrency)
  const body = result.parts.map(part => `  ${JSON.stringify(part)},`).join('\n')
  fs.writeFileSync(outFile, `${banner(path.basename(file))}export const ${exportName} = [\n${body}\n]\n`)
  console.log(`${path.basename(file)} -> ${path.basename(outFile.pathname || outFile)}`)
  console.log(`  ${result.parts.length} parts, ${result.report.adders} adders, ${result.currency}, ${(fs.statSync(outFile).size / 1024).toFixed(0)} kB`)
  result.report.sheets.forEach(sheet =>
    console.log(`   ${sheet.name}: ${sheet.parts} parts, ${sheet.adders} adders, ${sheet.skipped} rows skipped`))
  result.warnings.forEach(warning => console.log(`   ! ${warning}`))
  result.errors.forEach(error => console.error(`   ERROR ${error}`))
}

const [bnkFile, metrixFile] = process.argv.slice(2)
if (!bnkFile || !metrixFile) {
  console.error('usage: node scripts/convert-price-lists.mjs <bnk.xlsx> <metrix.xlsx>')
  process.exit(1)
}
const outDir = new URL('../src/priceListData/', import.meta.url)
fs.mkdirSync(outDir, { recursive: true })
convert(bnkFile, 'BNK_IMPORTED_PARTS', new URL('bnk.js', outDir), 'EUR')
convert(metrixFile, 'METRIX_IMPORTED_PARTS', new URL('metrix.js', outDir), 'USD')
